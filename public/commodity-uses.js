// Helper to look up a commodity description with case-insensitive partial matching
window.getCommodityUse = function(name){
  if(!name) return null;
  const lc = name.toLowerCase().trim();
  // exact match first
  for(const k in window.COMMODITY_USES){
    if(k.toLowerCase()===lc) return window.COMMODITY_USES[k];
  }
  // contains-match
  for(const k in window.COMMODITY_USES){
    if(lc.includes(k.toLowerCase()) || k.toLowerCase().includes(lc)) return window.COMMODITY_USES[k];
  }
  return null;
};
